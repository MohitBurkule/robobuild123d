"""BUILD.md (and a plain BUILD.html) from the pack data."""

from __future__ import annotations

import html


def _table(rows, cols):
    if not rows:
        return "_none_\n"
    s = "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n"
    for r in rows:
        s += "| " + " | ".join("" if r.get(c) is None else str(r.get(c)) for c in cols) + " |\n"
    return s


def markdown(name, data):
    b, m = data["buy"], data["mass"]
    md = [f"# Build guide: {name}\n", "> Generated by robot.mfg. UNTESTED first version: check against the renders.\n",
          f"## Mass budget\n\n{m['total_g']} g ± {m['tol_g']} g of {m['limit_g']} g, margin {m['margin_g']} g"
          f" ({'OK' if m['ok'] else 'CHECK'}).{' Unknown mass: ' + ', '.join(m['unknown']) if m['unknown'] else ''}\n",
          _table(m["lines"], ["id", "g", "source"]),
          "## Buy list\n", _table(b, ["name", "kind", "qty", "order_qty", "catalog", "source"]),
          "## Fasteners\n", _table([{"designation": k, "count": v} for k, v in data["fasteners"].items()],
                                   ["designation", "count"]),
          "## Print\n", _table(data["print"], ["id", "material", "up_axis", "supports", "walls", "infill_pct",
                                               "layer_mm", "nozzle_c", "bed_c"]),
          "## Cut\n", _table(data["cut"]["rows"], ["id", "material", "thickness_mm", "process", "bend", "dxf", "qty"]),
          "## Assembly\n"]
    for s in data["steps"]:
        md.append(f"{s['n']}. {s['text']}")
        for f in s["fasteners"]:
            md.append(f"   - {f['designation']} `{f['id']}`" + (f" into {f['into']}" if f["into"] else "")
                      + (f" ({f['tool']})" if f["tool"] else ""))
    md.append("\n## Files\n\n- `print/` STL + STEP per printed part, already in bed orientation\n"
              "- `cut/` DXF flats per sheet part\n- `step/assembly.step`\n- `bom.csv`, `pack.json`\n")
    return "\n".join(md)


def to_html(name, md):
    return (f"<!doctype html><meta charset=utf-8><title>{html.escape(name)} build</title>"
            "<style>body{font:15px system-ui;max-width:60em;margin:2em auto;padding:0 1em}</style>"
            f"<pre style='white-space:pre-wrap'>{html.escape(md)}</pre>")
