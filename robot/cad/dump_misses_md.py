"""Render dump_misses JSON results as review/code/MISSES.md.

    python -m robot.cad.dump_misses_md out.md notes.json part1.json [part2.json ...]

notes.json: {"<part>": {"<SW feature or extra:<i>>": {"what": "...", "cause": "...", "fix": "..."}}} - the reviewer's
diagnosis of each miss (what our code does and why); without a note the measured numbers and the heuristic category
are shown. Process fixes are grouped by kind (tool / guide / check) at the end.
"""
from __future__ import annotations

import collections
import json
import sys
from pathlib import Path

from .dump_misses import FIX

CHECKS = ("dump.fillet", "dump.hole", "dump.extrude", "reference_cad.diff")


def _cell(s):
    return str(s).replace("|", "/").replace("\n", " ")


def _counts(r):
    c = collections.Counter(x["status"] for x in r["rows"])
    return ", ".join(f"{k}: {v}" for k, v in sorted(c.items())) + (
        " (not shown = the reference STL shows none of the feature's sampled faces, or they are untyped 'surf' faces: NOT compared)"
        if c.get("not shown") else "")


def part_section(r, notes):
    n = notes.get(r["part"], {})
    out = [f"## {r['part']} vs `{r['dump']}` ({r['stl']})", "",
           f"Registration gap {r['reg_gap_mm']} mm. Volume ours {r['vol_ours']} / reference {r['vol_ref']} mm3 "
           f"({100 * (r['vol_ours'] / r['vol_ref'] - 1):+.2f} %). reference_cad tol_mm {r['tol_mm']}. "
           + _counts(r), "",
           "| SW feature | type | SW dims (mm) | ours | numbers | cause | caught by | process fix |",
           "|---|---|---|---|---|---|---|---|"]
    misses = []
    for x in r["rows"]:
        note = n.get(x["feature"], {})
        cause = note.get("cause") or x["category"] or ""
        what = note.get("what") or x["status"]
        fix = note.get("fix") or (FIX.get(cause) if cause else "") or ""
        dims = ", ".join(f"{k}={v:g}" for k, v in x["dims"].items()) if x["dims"] else ""
        caught = ", ".join(x["caught"]) or ("-" if x["status"] == "present" else "NOTHING")
        if x["waiver"]:
            caught += " (waived: " + x["waiver"][:80] + ")"
        out.append(f"| {x['feature']} | {x['type']} | {_cell(dims)} | {_cell(what)} | {_cell(x['numbers'])} | {_cell(cause)} | "
                   f"{_cell(caught)} | {_cell(fix)} |")
        if x["status"] in ("wrong", "missing"):
            misses.append((cause, x["caught"], fix, x["waiver"]))
    ex = [e for e in r.get("extra", []) if e["area_mm2"] >= 1.0]
    if ex:
        out += ["", "Extra geometry (our surface > 0.3 mm from any reference surface):", "",
                "| # | where (centroid, mm) | area mm2 | max gap | nearest SW feature | cause | caught by | process fix |",
                "|---|---|---|---|---|---|---|---|"]
        for i, e in enumerate(ex):
            note = n.get(f"extra:{i}", {})
            cause = note.get("cause") or ("waived" if e["waiver"] else "invented feature / patch")
            caught = note.get("caught") or ("reference_cad.diff" if e["max_gap"] > (r["tol_mm"] or 0.5) and not e["waiver"] else "NOTHING")
            if e["waiver"]:
                caught += " (waived: " + e["waiver"][:60] + ")"
            fix = note.get("fix") or FIX.get(cause, "check: per-face reference coverage (every our face must lie on a reference face)")
            out.append(f"| {i} | {e['centroid']} | {e['area_mm2']} | {e['max_gap']} | {e['near_feature']} | {_cell(note.get('what', '') + ' ' + cause)} | "
                       f"{_cell(caught)} | {_cell(fix)} |")
            misses.append((cause, [caught] if not caught.startswith("NOTHING") else [], fix, e["waiver"]))
    return out, misses


def render(results, notes):
    lines = ["# Hand-built parts vs the designer's SolidWorks feature trees", "",
             "Generated by `robot/cad/dump_misses.py` (measurement) and `dump_misses_md.py` (this table). The SolidWorks dump "
             "(dumps_v2) is used ONLY as ground truth for diagnosis; nothing of it goes into the model. Per SW feature: its "
             "faces (v2 FACE lines) are sampled, mapped into our world frame (asmdump placement + ICP) and measured against "
             "our part; samples the reference STL does not show are skipped. `ours`: present (<= 0.05 mm), wrong, missing "
             "(> 1 mm). `caught by`: which existing check flags it (dump.* = robot/checks/sldprt_dump.py, which itself "
             "reads the dump; reference_cad.diff = the dump-free mesh diff at the entry's tol_mm).", ""]
    allm = []
    for r in results:
        sec, m = part_section(r, notes.get("_parts", notes))
        lines += sec + [""]
        allm += [(r["part"],) + t for t in m]
    cats = collections.Counter(c for _p, c, *_ in allm)
    lines += ["## Summary: causes", "", "| cause | count | caught by dump-free checks | caught only by dump.* | caught by nothing |", "|---|---|---|---|---|"]
    for c, k in cats.most_common():
        rows = [m for m in allm if m[1] == c]
        free = sum(any(x.startswith("reference_cad") for x in m[2]) for m in rows)
        dump = sum(bool(m[2]) and not any(x.startswith("reference_cad") for x in m[2]) for m in rows)
        lines.append(f"| {c} | {k} | {free} | {dump} | {k - free - dump} |")
    lines += ["", "Blind spots: a miss \"caught only by dump.*\" is invisible to a designer without the dump; \"caught by nothing\" "
              "is invisible to every check.", "", "## Process fixes, grouped by kind", ""]
    kinds = collections.defaultdict(set)
    for m in allm:
        for part in str(m[3]).split(";"):
            part = part.strip()
            if ":" in part:
                k, v = part.split(":", 1)
                kinds[k.strip()].add(v.strip())
    for k in ("tool", "guide", "check"):
        if kinds.get(k):
            lines += [f"### {k}", ""] + [f"- {v}" for v in sorted(kinds[k])] + [""]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    out, notes = sys.argv[1], json.loads(Path(sys.argv[2]).read_text()) if Path(sys.argv[2]).is_file() else {}
    res = [json.loads(Path(p).read_text()) for p in sys.argv[3:]]
    Path(out).write_text(render(res, notes))
    print(out)
