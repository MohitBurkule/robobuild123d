"""Markdown / JSON writers."""
import json
import math


def _v(x, k=6):
    if x is None:
        return ''
    if isinstance(x, (list, tuple)):
        return '(' + ', '.join(_v(c, k) for c in x) + ')'
    if isinstance(x, float):
        return ('%.' + str(k) + 'g') % x
    return str(x)


def _mm(v):
    return _v([round(c * 1000, 4) for c in v]) if isinstance(v, (list, tuple)) else _v(round(v * 1000, 4))


def surf_desc(f):
    p = f['params'] or {}
    t = f['surface_type']
    if t == 'plane':
        return 'n=%s  d=%s mm  (pt %s mm)' % (_v(p['normal'], 4), _mm(p['offset_along_normal']), _mm(p['point']))
    if t == 'cylinder':
        return 'R=%s mm (Ø%s)  axis=%s  through %s mm' % (_mm(p['radius']), _mm(2 * p['radius']), _v(p['axis'], 4), _mm(p['point']))
    if t == 'cone':
        return 'R=%s mm half-angle=%s°  axis=%s  apex-side pt %s mm' % (_mm(p['radius']), _v(p['half_angle_deg'], 5), _v(p['axis'], 4), _mm(p['point']))
    if t == 'sphere':
        return 'R=%s mm  centre %s mm' % (_mm(p['radius']), _mm(p['centre']))
    if t == 'torus':
        return 'Rmaj=%s Rmin=%s mm axis=%s centre %s mm' % (_mm(p['major_radius']), _mm(p['minor_radius']), _v(p['axis'], 4), _mm(p['centre']))
    return '(params not decoded)'


def faces_md(r):
    o = ['# %s - faces (decoded from embedded Parasolid)\n' % r['file'].rsplit('.', 1)[0]]
    o.append('Generated by tools/decode_sldprt.py. Units: mm. See decoded/README.md for method and confidence.\n')
    for x in r['parasolid']:
        o.append('- Parasolid stream: modeller %s, schema %s, %d faces, %d surfaces, %d attributes' % (
            x['version'], x['schema'], x['faces'], x['surfaces'], x['attributes']))
    o.append('- Face types: ' + ', '.join('%s=%d' % kv for kv in sorted(r['face_summary'].items())))
    m = r['meta']
    if m.get('material'):
        mat = m['material']
        o.append('- Material: %s, density %s kg/m^3' % (mat.get('name'), mat.get('DENS', {}).get('value')))
    for k, v in (m.get('props', {}).get('mass_props') or {}).items():
        i = v['interpretation']
        if not i.get('volume_m3'):
            o.append('- %s: present but all zero (mass properties not computed when saved)' % k)
            continue
        o.append('- %s: CoG=(%s, %s, %s) mm, volume=%s mm^3, area=%s mm^2, mass=%s g, inertia terms %s' % (
            k, _mm(i.get('cog_x_m', 0)), _mm(i.get('cog_y_m', 0)), _mm(i.get('cog_z_m', 0)),
            _v(i.get('volume_m3', 0) * 1e9), _v(i.get('surface_area_m2', 0) * 1e6), _v(i.get('mass_kg', 0) * 1e3),
            _v(v['raw'][6:12], 4)))
    o.append('- Configurations: %s' % (', '.join('%s:%s' % c for c in m.get('configs', [])) or 'n/a'))
    o.append('- Equations found: %s' % ('; '.join(m.get('equations', [])) or 'none'))
    sc = r.get('step_check')
    if sc:
        o.append('- STEP cross-check (rvrn_2.0.step): best brep #%s %r, score %s (set Jaccard %s); cylinders part/step %d/%d; planes part/step %d/%d; radii only in part %s; only in STEP %s' % (
            sc['brep'], sc['name'], sc['score'], sc['set_jaccard'], sc['part_cyl'], sc['step_cyl'], sc['part_planes'], sc['step_planes'],
            sc['radii_only_in_part'], sc['radii_only_in_step']))
    stc = r.get('structural') or {}
    if stc:
        c = stc['container']
        o.append('- Structural coverage: container %s%% (%d sections, %d CRC-verified, %d opaque, %d unframed streams); ' % (
            c['coverage_pct'], c['sections'], c['crc_ok'], c['opaque_sections'], c['unframed_streams'])
            + '; '.join('XT@%s %s%% (%d nodes, faces seq %s, agree %s, gap types %s)' % (x['offset'], x['coverage_pct'], x['nodes'], x['faces_sequential'], x['faces_agree_with_pattern_reader'], x['gap_start_types']) for x in stc.get('parasolid', []))
            + ('; feature stream %s%% %s' % (stc['feature_stream']['coverage_pct'], stc['feature_stream']['records']) if stc.get('feature_stream') else ''))
    o.append('\n"first" = earliest-timestamp ATOM_ID_2001 feature on the face (most likely creator); "last" = latest modifier; all = every feature id seen on the face (chronological).\n')
    o.append('| # | type | geometry | creator (first) | last | all feature ids |')
    o.append('|---|---|---|---|---|---|')
    for k, f in enumerate(r['faces']):
        o.append('| %d | %s | %s | %s %s | %s %s | %s |' % (
            k, f['surface_type'], surf_desc(f), f['feature_first'], f['feature_first_name'] or '?',
            f['feature_last'], f['feature_last_name'] or '?', ','.join(map(str, f['feature_ids_by_time']))))
    o.append('\n## Face boundaries (XT loops)\n')
    o.append('Per face: loops as edge lists; vertex = fin start vertex (mm); curve type. Full curve params in JSON.\n')
    for k, f in enumerate(r['faces']):
        ls = []
        for L in f.get('loops', []):
            ls.append(' -> '.join('%s%s' % ((e['curve'] or {}).get('type', '?')[:4], _mm(e['start_vertex']) if e['start_vertex'] else '') for e in L['edges']))
        o.append('- face %d (%d loops; adjacent %s): %s' % (k, len(f.get('loops', [])), f.get('adjacent_faces', []), ' || '.join(ls)))
    fp = r.get('feature_params') or {}
    if fp:
        o.append('\n## Feature parameters (inferred; see README)\n')
        for fid, v in fp.items():
            o.append('- %s %s: %s' % (fid, v['name'], '; '.join('%s=%s' % (k, v[k]) for k in v if k not in ('name', 'type'))))
    if r.get('ref_planes'):
        o.append('\n## Reference planes (low confidence)\n')
        for p in r['ref_planes']:
            o.append('- %s dims %s transform %s' % (p['name'], p['dims'], _v(p['transform_rows_x_y_n_t'], 5) if p['transform_rows_x_y_n_t'] else '?'))
    o.append('\n## Features (Keywords)\n')
    o.append('| id | name | type | dims |')
    o.append('|---|---|---|---|')
    for f in r['features']:
        o.append('| %d | %s | %s | %s |' % (f['id'], f['name'], f['type'], ', '.join('%s=%s' % d for d in f['dims'])))
    return '\n'.join(o) + '\n'


def sketches_md(r):
    o = ['# %s - sketches (decoded from feature stream)\n' % r['file'].rsplit('.', 1)[0]]
    o.append('Sketch-local coordinates in mm. Placement = 3x3 rows (sketch X, Y, normal) + origin, world = t + x*X + y*Y. Confidence per sketch below; see README.\n')
    if r.get('sketches_not_located'):
        o.append('Not located in stream: %s\n' % ', '.join(r['sketches_not_located']))
    for s in r['sketches']:
        o.append('## %s%s' % (s['name'], ' (used by %s)' % ', '.join(s['used_by']) if s['used_by'] else ''))
        p = s.get('placement')
        if p:
            T = p['transform_rows_x_y_z_t']
            o.append('- placement [%s]: X=%s Y=%s N=%s origin=%s mm; score %s, %s arcs on XT cylinders, %d tied candidates' % (
                p['confidence'], _v(T[0:3], 4), _v(T[3:6], 4), _v(T[6:9], 4), _mm(list(T[9:12])), p['score'],
                p['arcs_matching_xt_cylinders'], p['n_tied']))
        o.append('- dims (Keywords): %s' % (', '.join('%s=%s' % d for d in s['dims']) or 'none'))
        for dm in s['dim_matches']:
            if dm['matches']:
                o.append('  - %s=%s -> %s' % (dm['dim'], dm['value'], '; '.join(
                    ('%s#%s %s' % (m[2], m[1], m[3])) if m[0] == 'entity' else ('pts %s-%s %s' % (m[1], m[2], m[3])) for m in dm['matches'][:6])))
            else:
                o.append('  - %s=%s -> no geometric match%s' % (dm['dim'], dm['value'], (' (' + dm['note'] + ')') if dm.get('note') else ''))
        o.append('\n| pt | x | y | ext-ref |')
        o.append('|---|---|---|---|')
        for i, q in enumerate(s['points']):
            o.append('| %d | %s | %s | %s |' % (i, _mm(q['x']) if q['x'] is not None else '?', _mm(q['y']) if q['y'] is not None else '?', 'y' if q['ext'] else ''))
        o.append('\n| ent | type | start | end | centre | R / L mm | flag | notes |')
        o.append('|---|---|---|---|---|---|---|---|')
        for i, e in enumerate(s['entities']):
            rl = _mm(e['radius']) if 'radius' in e else (_mm(e['length']) if 'length' in e else '')
            notes = []
            if 'sweep_ccw_deg' in e:
                notes.append('sweep(ccw?) %.2f°' % e['sweep_ccw_deg'])
            if e.get('radius_mismatch', 0) > 1e-7:
                notes.append('radius mismatch %.2e' % e['radius_mismatch'])
            if e.get('length') == 0:
                notes.append('zero length')
            o.append('| %d | %s | %s | %s | %s | %s | %s | %s |' % (
                i, e['type'], e['start_idx'], e['end_idx'], e.get('centre_idx', ''), rl, e['flag'], '; '.join(notes)))
        o.append('')
    return '\n'.join(o) + '\n'


def to_json(r):
    def clean(x):
        if isinstance(x, float):
            return None if math.isnan(x) or math.isinf(x) else round(x, 12)
        if isinstance(x, dict):
            return {str(k): clean(v) for k, v in x.items()}
        if isinstance(x, (list, tuple)):
            return [clean(v) for v in x]
        return x
    return json.dumps(clean(r), indent=1)
